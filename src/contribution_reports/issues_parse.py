"""This module provides schema-tolerant parsing, sanitization, and normalization
for LLM output.

We use the rubric building logic and shared helper functions here to coerce
various model-generated JSON shapes into canonical internal forms.
"""

import json
import re
from typing import TYPE_CHECKING

from .constants import DIMENSIONS
from .issues_prompts import _RUBRIC_SYSTEM

if TYPE_CHECKING:
    from .llm import LLMClient

# Longest and most specific patterns appear first. These serve as a backstop to
# system-prompt instructions for all LLM-generated free text, including issue
# summaries, note summaries, and rubric answer or threshold labels.
#
# The report must never assert a legal-compliance or ADA status regardless of
# what wording appears in survey notes or underlying quest tags. Such claims
# require a legal determination, which a rubric or LLM summary should not
# claim.
_LEGAL_TERM_SUBS: list[tuple[re.Pattern, str]] = [
    (re.compile(r"\bAmericans with Disabilities Act\b", re.IGNORECASE), "accessibility guidelines"),
    (re.compile(r"\bA\.D\.A\.", re.IGNORECASE), "accessibility"),
    (re.compile(r"\bnon[-\s]?ada[-\s]?compliant\b", re.IGNORECASE), "not accessible"),
    (re.compile(r"\bada[-\s]?compliant\b", re.IGNORECASE), "accessible"),
    (re.compile(r"\bada[-\s]?complian(t|ce)\b", re.IGNORECASE), "accessibility"),
    (re.compile(r"\bada\b", re.IGNORECASE), "accessibility"),
    (re.compile(r"\bnon[-\s]?compliant\b", re.IGNORECASE), "not accessible"),
    (re.compile(r"\bcompliant\b", re.IGNORECASE), "accessible"),
    (re.compile(r"\bcompliance\b", re.IGNORECASE), "accessibility"),
    (re.compile(r"\bcomplies\b", re.IGNORECASE), "conforms"),
    (re.compile(r"\bcomply\b", re.IGNORECASE), "conform"),
]


def _scrub_legal_terms(text: str) -> str:
    """Removes legal-compliance and ADA wording from text generated by the LLM.

    We apply this only to content authored by the LLM, such as summaries and
    labels. Raw note text and survey answer values remain unchanged because
    they represent original input displayed verbatim as evidence instead of an
    inferred claim.
    """
    if not text:
        return text
    scrubbed = text
    for pattern, repl in _LEGAL_TERM_SUBS:
        scrubbed = pattern.sub(repl, scrubbed)
    return re.sub(r"\s{2,}", " ", scrubbed).strip()

def _unwrap_list_result(result: object, known_keys: tuple[str, ...] = ()) -> list:
    """Coerce a ``complete_json`` result into a list, tolerating wrapper shapes.

    Cloud models (Claude) reliably return a bare JSON array when asked for
    one. Local models served through Ollama's ``format: "json"`` constrained
    decoding often cannot emit a top-level array and instead wrap it in a
    single-key object under some model-invented name (``results``, ``items``,
    ...) rather than the name we asked for. Rather than chase every model's
    naming choice, accept any of ``known_keys`` first, then fall back to the
    sole list-valued key if there's exactly one.
    """
    if isinstance(result, list):
        return result
    if isinstance(result, dict):
        for key in known_keys:
            val = result.get(key)
            if isinstance(val, list):
                return val
        list_values = [v for v in result.values() if isinstance(v, list)]
        if len(list_values) == 1:
            return list_values[0]
    return []

def _entries_from_flat_map(flat: dict) -> list[dict]:
    """Transforms a flat ``{quest_tag: {answer_value: {weight, label, ...}}}`` map
    into rubric entries while skipping corrupted tags. Because downstream
    components provide safe defaults for ``quest_type``, ``dimensions``, and
    ``default_weight``, we can use this bare tag->answers map when local models
    fail to return the expected list-of-entries.

    A tag's value may contain per-answer ``{weight, label}`` dicts alongside
    scalar metadata like ``default_weight``, ``dimensions``, or ``note``. We
    see this with free-text quests that provide a fallback weight instead of
    discrete answer choices. If a tag's value is already a list of
    ``{value, weight, label, dimensions?}`` objects, we pass it through
    as-is--this matches the canonical ``answers`` shape used elsewhere.

    We skip individual tags that use unrecognized shapes or contain malformed
    answer entries (such as a hallucinated field mixed into a string) instead
    of aborting the entire map. This handles cases where one bad answer appears
    among 30+ valid tags. An empty return indicates to the caller that this
    shape does not apply.
    """
    entries = []
    for tag, val in flat.items():
        if isinstance(val, list):
            good = [a for a in val if isinstance(a, dict) and "weight" in a]
            if good:
                entries.append({"quest_tag": tag, "answers": good})
            continue
        if not (isinstance(val, dict) and val):
            continue
        answers = {k: v for k, v in val.items() if isinstance(v, dict) and "weight" in v}
        meta = {k: v for k, v in val.items() if k not in answers}
        if answers or "default_weight" in meta:
            entries.append({"quest_tag": tag, "answers": answers, **meta})
    return entries


def _build_rubric(llm: "LLMClient", quest_def: dict) -> dict:
    """Generates a signed severity rubric via an LLM and returns it as a
    `{quest_tag: rubric_entry}` mapping.

    Because models often mirror the nested structure of the quest definition
    (`element_type` -> `quests[]`), we flatten the response into a simple
    `{quest_tag -> entry}` dictionary. We perform this normalization to
    reconcile differences between local (Ollama) and cloud (Claude) models,
    which includes resolving wrapper keys like `rubric`, `elements`, or
    `quest_weights`. We also alias entry fields such as `answer_weights`,
    `weights`, or `choices` to `answers`. If the LLM provides `answers` as a
    dictionary keyed by value, we convert it to a list. Finally, we handle
    cases where `dimensions` appear in a sibling `quest_dimensions` map instead
    of inside each entry.
    """
    user = (
        "Here is the quest definition for this workspace survey:\n\n"
        + json.dumps(quest_def, indent=2)
        + "\n\nGenerate a severity rubric mapping each quest answer to a signed "
          "weight in [-1, +1] and classifying each quest into one or more "
          "dimensions (traversability, connectivity, safety_comfort)."
    )
    result = llm.complete_json(_RUBRIC_SYSTEM, user, max_tokens=65535, label="rubric")

    top_list = _unwrap_list_result(result, known_keys=("rubric", "elements", "quest_weights", "quests"))
    if not top_list and isinstance(result, dict):
        top_list = _entries_from_flat_map(result)
        if not top_list:
            for val in result.values():
                if isinstance(val, dict):
                    top_list = _entries_from_flat_map(val)
                    if top_list:
                        break

    # Certain models avoid nesting dimensions within each entry, instead
    # splitting them into a sibling map.
    #
    #     {"quest_weights": {...}, "quest_dimensions": {tag: [...]}}.
    dims_by_tag = result.get("quest_dimensions") if isinstance(result, dict) else None

    raw_entries: list[dict] = []
    for item in top_list:
        if not isinstance(item, dict):
            continue
        if "quest_tag" in item:
            raw_entries.append(item)
        elif "quests" in item:
            for q in item.get("quests", []):
                if isinstance(q, dict) and "quest_tag" in q:
                    raw_entries.append(q)

    rubric_map: dict = {}
    for entry in raw_entries:
        # This code identifies the correct OSM quest tag key. Certain local
        # models populate the quest_tag field with numeric IDs while storing
        # the actual tag name (such as ext:sidewalk_condition) in a separate
        # tag field. The logic prioritizes any value resembling an OSM or ext:
        # tag, falling back to quest_tag if no better candidate exists.
        candidate = entry.get("tag") or entry.get("quest_tag") or ""
        tag = None
        for c in [candidate]:
            if isinstance(c, str) and (c.startswith("ext:") or ":" not in c.split(".")[0] and len(c) > 2):
                tag = c
                break
        if tag is None:
            # The code falls back to whatever `quest_tag` exists. Downstream
            # processes will not match any element tags when we provide garbage
            # IDs, which is the correct behavior.
            tag = candidate or ""
        if not tag:
            continue

        # Normalise answer list
        if "answers" not in entry:
            for alias in ("answer_weights", "weights", "choices"):
                if alias in entry:
                    entry["answers"] = entry.pop(alias)
                    break
        answers = entry.get("answers")
        if isinstance(answers, dict):
            answers = [
                {
                    "value": val, "weight": a.get("weight"), "label": a.get("label", val),
                    **({"dimensions": a["dimensions"]} if isinstance(a.get("dimensions"), list) else {}),
                }
                for val, a in answers.items()
                if isinstance(a, dict)
            ]
        entry["answers"] = answers or []
        for ans in entry["answers"]:
            if "label" not in ans:
                ans["label"] = ans.get("value", "")
            ans["label"] = _scrub_legal_terms(ans["label"])
        for thresh in entry.get("thresholds", []) or []:
            if isinstance(thresh, dict) and thresh.get("label"):
                thresh["label"] = _scrub_legal_terms(thresh["label"])
        # Dimensions require normalization. We use the entry-level field first,
        # then the sibling map if it exists. If neither provides data, we take
        # the union of dimensions across answers (this handles shapes that
        # classify dimensions per-answer instead of per-quest).
        dims = entry.get("dimensions")
        if not dims and dims_by_tag:
            dims = dims_by_tag.get(tag)
        if not dims:
            answer_dims = list(dict.fromkeys(
                d for ans in entry["answers"] if isinstance(ans.get("dimensions"), list)
                for d in ans["dimensions"]
            ))
            dims = answer_dims or None
        entry["dimensions"] = _normalise_dims(dims)
        rubric_map[tag] = entry

    return rubric_map

def _normalise_dims(raw: object) -> list[str]:
    """Normalizes an LLM dimension value into a validated list."""
    valid = set(DIMENSIONS)
    if isinstance(raw, list):
        result = [d for d in raw if d in valid]
        return result if result else ["traversability"]
    if isinstance(raw, str) and raw in valid:
        return [raw]
    return ["traversability"]
